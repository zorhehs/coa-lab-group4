#!/usr/bin/env python3
"""
Reproduce every figure and table used in the report.

    python3 scripts/experiments.py            # writes results/*.svg, results/*.csv, results/summary.md

Standard library only; the charts are the same SVG style as the GUI.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from cachesim import CacheConfig, Cache, parse_trace, sweep, rows_to_csv  # noqa: E402
from cachesim.charts import bar_chart_svg, line_chart_svg  # noqa: E402

DATA = os.path.join(ROOT, "data")
OUT = os.path.join(ROOT, "results")
os.makedirs(OUT, exist_ok=True)


def load(name):
    with open(os.path.join(DATA, name)) as fh:
        return parse_trace(fh.read())


def write(name, text):
    path = os.path.join(OUT, name)
    with open(path, "w") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def series_from_rows(rows, metric):
    cats, series = [], {}
    for r in rows:
        if r["label"] not in cats:
            cats.append(r["label"])
    for r in rows:
        key = r["series"] or metric
        series.setdefault(key, [None] * len(cats))
        if "stats" in r:
            series[key][cats.index(r["label"])] = r["stats"][metric]
    return cats, series


summary = ["# Experiment summary", "",
           "Generated by `scripts/experiments.py`. All traces are in `data/`; every number below is",
           "reproducible with the CLI commands shown.", ""]


def md_table(rows, metrics):
    head = "| series | config | " + " | ".join(metrics) + " |"
    sep = "|---|---|" + "|".join(["---:"] * len(metrics)) + "|"
    out = [head, sep]
    for r in rows:
        if "error" in r:
            out.append("| %s | %s | %s |" % (r["series"] or "-", r["label"], "n/a: " + r["error"]))
            continue
        cells = []
        for m in metrics:
            v = r["stats"][m]
            cells.append("%.4f" % v if isinstance(v, float) else str(v))
        out.append("| %s | %s | %s |" % (r["series"] or "-", r["label"], " | ".join(cells)))
    return "\n".join(out)


# ------------------------------------------------------------------ #
# 1. Associativity x replacement policy on the conflict trace
# ------------------------------------------------------------------ #
trace = load("conflict.trace")
base = CacheConfig(cache_size=1024, block_size=16)
rows = sweep(base, trace, "associativity", [1, 2, 4, 8, 0], "replacement", ["LRU", "FIFO", "RANDOM"])
cats, ser = series_from_rows(rows, "hit_ratio")
write("fig1_assoc_vs_policy_conflict.svg", bar_chart_svg("Hit ratio vs associativity (conflict trace)", cats, ser,
      ylabel="hit ratio", subtitle="1 KiB cache, 16 B blocks; three blocks 1 KiB apart, repeated 16x"))
write("fig1_assoc_vs_policy_conflict.csv", rows_to_csv(rows))
summary += ["## 1. Associativity x replacement policy, conflict trace", "",
            "`python -m cachesim sweep --trace data/conflict.trace --param associativity --values 1,2,4,8,0 --series replacement --series-values LRU,FIFO,RANDOM`", "",
            md_table(rows, ["hit_ratio", "compulsory", "capacity", "conflict", "amat"]), ""]

# ------------------------------------------------------------------ #
# 2. Block size sweep on sequential / random / matrix traces (spatial locality)
# ------------------------------------------------------------------ #
series = {}
cats = None
for name in ["sequential.trace", "matrix_row.trace", "matrix_col.trace", "random.trace"]:
    rows = sweep(CacheConfig(cache_size=1024, block_size=16, associativity=4), load(name), "block_size", [4, 8, 16, 32, 64, 128])
    c, s = series_from_rows(rows, "miss_ratio")
    cats = c
    series[name.replace(".trace", "")] = s["miss_ratio"]
write("fig2_block_size_vs_trace.svg", line_chart_svg("Miss ratio vs block size", cats, series, ylabel="miss ratio",
      subtitle="1 KiB, 4-way, LRU, write-back; one line per access pattern"))
summary += ["## 2. Block size vs access pattern (1 KiB, 4-way LRU)", "",
            "`python -m cachesim sweep --trace data/<trace> --size 1024 --assoc 4 --param block_size --values 4,8,16,32,64,128 --metric miss_ratio`", "",
            "| block size | " + " | ".join(series) + " |", "|---|" + "|".join(["---:"] * len(series)) + "|"]
for i, c in enumerate(cats):
    summary.append("| %s | %s |" % (c, " | ".join("%.4f" % series[k][i] for k in series)))
summary.append("")

# ------------------------------------------------------------------ #
# 3. Cache size sweep on loop_large (capacity misses)
# ------------------------------------------------------------------ #
trace = load("loop_large.trace")
rows = sweep(CacheConfig(cache_size=1024, block_size=16, associativity=4), trace, "cache_size", [256, 512, 1024, 2048, 4096, 8192])
cats, ser = series_from_rows(rows, "miss_ratio")
stack = {k: [r["stats"][k] if "stats" in r else None for r in rows] for k in ("compulsory", "capacity", "conflict")}
write("fig3_cache_size_miss_types_loop_large.svg", bar_chart_svg("Miss breakdown vs cache size (loop_large)", cats, stack,
      ylabel="misses", value_fmt="{:.0f}", subtitle="16 B blocks, 4-way LRU; 2 KiB working set swept 3x"))
write("fig3_cache_size_loop_large.csv", rows_to_csv(rows))
summary += ["## 3. Cache size vs miss type, loop_large (2 KiB working set)", "",
            "`python -m cachesim sweep --trace data/loop_large.trace --assoc 4 --param cache_size --values 256,512,1024,2048,4096,8192`", "",
            md_table(rows, ["hit_ratio", "miss_ratio", "compulsory", "capacity", "conflict", "amat"]), ""]

# ------------------------------------------------------------------ #
# 4. Write policies: memory traffic on the loop trace (25% writes)
# ------------------------------------------------------------------ #
trace = load("loop.trace")
rows = sweep(CacheConfig(cache_size=1024, block_size=16, associativity=4), trace, "write_policy", ["WB", "WT"], "write_allocate", [True, False])
cats, ser_w = series_from_rows(rows, "mem_writes")
_, ser_t = series_from_rows(rows, "traffic_kib")
write("fig4_write_policy_mem_writes_loop.svg", bar_chart_svg("Memory write operations by write policy (loop)", cats, ser_w,
      ylabel="memory writes", value_fmt="{:.0f}", subtitle="1 KiB, 4-way LRU; 768 accesses, 25% writes; series = write-allocate / no-write-allocate"))
write("fig4_write_policy_traffic_loop.svg", bar_chart_svg("Memory traffic by write policy (loop)", cats, ser_t,
      ylabel="KiB", value_fmt="{:.2f}", subtitle="block fetches + write-backs (WB) or word writes (WT)"))
write("fig4_write_policy_loop.csv", rows_to_csv(rows))
summary += ["## 4. Write policy x allocation, loop trace (25% writes)", "",
            "`python -m cachesim sweep --trace data/loop.trace --assoc 4 --param write_policy --values WB,WT --series write_allocate --series-values 1,0 --metric mem_writes`", "",
            md_table(rows, ["hit_ratio", "write_misses", "writebacks", "mem_reads", "mem_writes", "traffic_kib"]), ""]

# ------------------------------------------------------------------ #
# 5. Victim cache extension on strided + conflict traces (direct mapped)
# ------------------------------------------------------------------ #
series = {}
for name in ["conflict.trace", "strided.trace", "matrix_col.trace"]:
    rows = sweep(CacheConfig(cache_size=1024, block_size=16, associativity=1), load(name), "victim_entries", [0, 2, 4, 8])
    cats, s = series_from_rows(rows, "amat")
    series[name.replace(".trace", "")] = s["amat"]
write("fig5_victim_cache_amat.svg", bar_chart_svg("AMAT vs victim cache size (direct mapped)", cats, series,
      ylabel="AMAT (cycles)", value_fmt="{:.1f}", subtitle="1 KiB DM, 16 B blocks; hit 1, miss 100, victim hit 2 cycles"))
summary += ["## 5. Victim cache (extension), direct-mapped 1 KiB", "",
            "`python -m cachesim sweep --trace data/conflict.trace --assoc 1 --param victim_entries --values 0,2,4,8 --metric amat`", "",
            "| victim entries | " + " | ".join(series) + " |", "|---|" + "|".join(["---:"] * len(series)) + "|"]
for i, c in enumerate(cats):
    summary.append("| %s | %s |" % (c, " | ".join("%.2f" % series[k][i] for k in series)))
summary.append("")

# ------------------------------------------------------------------ #
# 6. All traces under one reference configuration
# ------------------------------------------------------------------ #
ref = CacheConfig(cache_size=1024, block_size=16, associativity=4)
names = sorted(n for n in os.listdir(DATA) if n.endswith(".trace"))
cats, hr, mr, am = [], [], [], []
lines = ["| trace | accesses | hit ratio | compulsory | capacity | conflict | AMAT |", "|---|---:|---:|---:|---:|---:|---:|"]
for n in names:
    cache = Cache(ref)
    tr = load(n)
    cache.run(tr, keep_events=0)
    r = cache.results()
    cats.append(n.replace(".trace", ""))
    hr.append(r["hit_ratio"])
    am.append(r["amat"])
    lines.append("| %s | %d | %.4f | %d | %d | %d | %.2f |" % (n, r["accesses"], r["hit_ratio"], r["compulsory"], r["capacity"], r["conflict"], r["amat"]))
write("fig6_all_traces_reference_config.svg", bar_chart_svg("Hit ratio per trace, reference configuration", cats, {"hit ratio": hr},
      ylabel="hit ratio", subtitle="1 KiB, 16 B blocks, 4-way, LRU, write-back / write-allocate", width=900))
summary += ["## 6. Every trace under the reference configuration (1 KiB, 16 B, 4-way, LRU, WB/WA)", "",
            "`python -m cachesim run --trace data/<trace> --size 1024 --block 16 --assoc 4`", ""] + lines + [""]

write("summary.md", "\n".join(summary))
print("done")
